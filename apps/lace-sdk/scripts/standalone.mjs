// Generates the SDK's standalone public repository (ADR 66) from this
// monorepo: the SDK's packages (@laceio/sdk, and the Cardano domain layer and
// hardware wallet packages of ADR 68) and exactly the workspace packages they
// reach, with a root package.json and lockfile of their own. The developer
// site stays here: it documents the published packages and deploys from this
// repository.
//
//   node scripts/standalone.mjs allowlist <file>
//     Writes the rsync-style allowlist the mirror tooling's snapshot assembler
//     copies (tools/open-source-release).
//   node scripts/standalone.mjs transform <snapshot-dir>
//     Turns the copied tree into a repository that installs and builds on its
//     own: rewrites workspace package.json files, writes the root package.json
//     and .npmrc, and derives package-lock.json from this repository's lockfile,
//     so every version is the one this monorepo builds and tests.
import fs from 'node:fs';
import path from 'node:path';

import ts from 'typescript';

import {
  channelEntries,
  compilerOptions,
  packageDirectory,
  CARDANO_APPS,
  cardanoReachedFiles,
  reachedWorkspaceFiles,
  workspacePackages,
} from './reach.mjs';

const repositoryRoot = path.resolve(packageDirectory, '../..');
const SDK = 'apps/lace-sdk';
/**
 * Declarations for dependencies whose own a build cannot resolve, installed as
 * @types/* workspaces. TypeScript includes every installed @types package, so
 * without them the published declarations type those values as any.
 */
const TYPE_SHIMS = 'packages/types';
/** Root files the SDK's build and tests resolve from the repository root. */
const ROOT_FILES = [
  '.editorconfig',
  '.gitignore',
  '.nvmrc',
  '.prettierignore',
  '.prettierrc',
  'declarations.d.ts',
  'tsconfig.base.json',
  'tsconfig.test.json',
  'vitest.base.config.js',
];
/** Tools the SDK's build and tests run, declared at the monorepo root. */
const ROOT_TOOLS = [
  '@rolldown/plugin-node-polyfills',
  '@types/node',
  'prettier',
  'rolldown',
  'rollup',
  'rollup-plugin-dts',
  // The Cardano packages' build check compares installed versions with
  // their declared ranges.
  'semver',
  'tsdown',
  'typescript',
  'vitest',
  // The release notes read the changelog fragments (release-scope.ts), which
  // the tests cover.
  'yaml',
];

const readJson = file => JSON.parse(fs.readFileSync(file, 'utf8'));
const writeJson = (file, value) =>
  fs.writeFileSync(file, JSON.stringify(value, undefined, 2) + '\n');

const testFiles = () =>
  fs
    .readdirSync(path.join(packageDirectory, 'test'), { recursive: true })
    .filter(file => /\.tsx?$/.test(file))
    .map(file => path.join(packageDirectory, 'test', file));

/** The workspace packages the SDK's entries (both channels) and tests reach. */
export const sdkPackages = () => {
  const options = compilerOptions();
  const files = [
    ...reachedWorkspaceFiles(channelEntries('canary'), options),
    ...reachedWorkspaceFiles(
      channelEntries('stable'),
      compilerOptions('stable'),
    ),
    ...reachedWorkspaceFiles(testFiles(), { ...options, noEmit: true }),
  ];
  return workspacePackages(files, repositoryRoot);
};

/**
 * The workspace packages the Cardano packages' sources reach, resolved with the
 * declaration build's configuration, which their builds inline.
 */
const cardanoPackages = () =>
  workspacePackages(cardanoReachedFiles(), repositoryRoot);

const writeAllowlist = file => {
  const lines = [
    "# Generated by apps/lace-sdk/scripts/standalone.mjs: the SDK's packages",
    '# and the workspace packages they reach.',
    ...ROOT_FILES.map(name => `+ /${name}`),
    ...[SDK, ...CARDANO_APPS].map(app => `+ /${app}/***`),
    `+ /${TYPE_SHIMS}/***`,
    ...[...new Set([...sdkPackages(), ...cardanoPackages()])]
      .sort()
      .map(directory => `+ /${directory}/***`),
  ];
  fs.writeFileSync(file, lines.join('\n') + '\n');
  // eslint-disable-next-line no-console -- generator report
  console.log(`[standalone] allowlist: ${lines.length - 2} rules -> ${file}`);
};

const DEPENDENCY_FIELDS = [
  'dependencies',
  'devDependencies',
  'optionalDependencies',
  'peerDependencies',
];

/** Workspace directories in the snapshot that have a package.json. */
const snapshotWorkspaces = snapshot => [
  SDK,
  ...CARDANO_APPS.filter(app =>
    fs.existsSync(path.join(snapshot, app, 'package.json')),
  ),
  ...['contract', 'lib', 'module', 'next', 'types'].flatMap(kind => {
    const directory = path.join(snapshot, 'packages', kind);
    return fs.existsSync(directory)
      ? fs
          .readdirSync(directory)
          .map(name => `packages/${kind}/${name}`)
          .filter(name =>
            fs.existsSync(path.join(snapshot, name, 'package.json')),
          )
      : [];
  }),
];

/**
 * The lock entry a dependency of `from` resolves to, by Node's lookup: the
 * nearest node_modules directory up from `from`, then the root.
 */
const resolveInLock = (packages, from, name) => {
  let base = from;
  for (;;) {
    const candidate = base
      ? `${base}/node_modules/${name}`
      : `node_modules/${name}`;
    if (packages[candidate]) return candidate;
    if (!base) return undefined;
    const parent = base.lastIndexOf('/node_modules/');
    base =
      parent >= 0
        ? base.slice(0, parent)
        : base.startsWith('node_modules/')
        ? ''
        : '';
  }
};

const transform = snapshot => {
  const rootPackage = readJson(path.join(repositoryRoot, 'package.json'));
  const rootLock = readJson(path.join(repositoryRoot, 'package-lock.json'));
  const workspaces = snapshotWorkspaces(snapshot);
  const nameToDirectory = Object.fromEntries(
    workspaces.map(directory => [
      readJson(path.join(snapshot, directory, 'package.json')).name,
      directory,
    ]),
  );

  // Workspace package.json files keep only the @lace-* packages present.
  for (const directory of workspaces) {
    const file = path.join(snapshot, directory, 'package.json');
    const manifest = readJson(file);
    for (const field of DEPENDENCY_FIELDS) {
      if (!manifest[field]) continue;
      for (const name of Object.keys(manifest[field])) {
        if (/^@lace-/.test(name) && !nameToDirectory[name]) {
          delete manifest[field][name];
        }
      }
    }
    // An optional dependency installed from a registry the public cannot read
    // (an organisation's GitHub Packages) is not part of what the SDK needs: it
    // leaves the repository, manifest and lockfile both.
    for (const name of Object.keys(manifest.optionalDependencies ?? {})) {
      const key = resolveInLock(rootLock.packages, directory, name);
      if (key && !isPublic(rootLock.packages[key])) {
        delete manifest.optionalDependencies[name];
      }
    }
    delete manifest.scripts?.postinstall;
    writeJson(file, manifest);
  }

  const rootDeclared = {
    ...rootPackage.optionalDependencies,
    ...rootPackage.dependencies,
    ...rootPackage.devDependencies,
  };
  const declaredByWorkspaces = new Set(
    workspaces.flatMap(directory => {
      const manifest = readJson(path.join(snapshot, directory, 'package.json'));
      return DEPENDENCY_FIELDS.flatMap(field =>
        Object.keys(manifest[field] ?? {}),
      );
    }),
  );
  // Each tool at the version the monorepo declares it, or locks it at.
  const devDependencies = {};
  for (const name of ROOT_TOOLS) {
    if (declaredByWorkspaces.has(name)) continue;
    const version =
      rootDeclared[name] ?? rootLock.packages[`node_modules/${name}`]?.version;
    if (!version) throw new Error(`${name} is neither declared nor locked`);
    devDependencies[name] = version;
  }
  // Packages the workspace code imports without declaring, resolved through the
  // monorepo root: declared at the new root at the version the root declares,
  // or else the version the root lockfile installs.
  const dependencies = {};
  for (const name of importedPackages(snapshot, workspaces)) {
    if (declaredByWorkspaces.has(name) || devDependencies[name]) continue;
    if (/^@lace-/.test(name) || /^@laceio\//.test(name)) continue;
    const locked = rootLock.packages[`node_modules/${name}`];
    // A package from a registry the public cannot read is imported only by
    // code the SDK does not reach (it would be declared otherwise).
    if (locked && !isPublic(locked)) continue;
    const version = rootDeclared[name] ?? locked?.version;
    if (version) dependencies[name] = version;
    // Its types, where they ship as a separate @types package.
    const types = `@types/${name.replace(/^@([^/]+)\//, '$1__')}`;
    const typesVersion =
      rootDeclared[types] ??
      rootLock.packages[`node_modules/${types}`]?.version;
    if (typesVersion && !declaredByWorkspaces.has(types)) {
      dependencies[types] = typesVersion;
    }
  }

  const newRoot = {
    name: 'lace-sdk-repository',
    private: true,
    description:
      'The Lace SDK: @laceio/sdk, the Cardano domain layer @laceio/cardano and its hardware wallet packages, and the workspace packages they build from.',
    license: rootPackage.license,
    engines: rootPackage.engines,
    workspaces,
    scripts: {
      // The SDK imports @laceio/cardano, and its build's checks load and
      // type-check against that package's build, so it builds first.
      build: `bash apps/lace-cardano/scripts/build.sh && bash ${SDK}/scripts/build.sh`,
      'build:cardano': CARDANO_APPS.map(
        app => `bash ${app}/scripts/build.sh`,
      ).join(' && '),
      test: `cd ${SDK} && NODE_OPTIONS=--experimental-require-module vitest run --config=vitest.config.js && node test/check-stable-variants.mjs`,
    },
    dependencies: sortKeys(dependencies),
    devDependencies: sortKeys(devDependencies),
    overrides: rootPackage.overrides,
  };
  writeJson(path.join(snapshot, 'package.json'), newRoot);
  fs.writeFileSync(
    path.join(snapshot, '.npmrc'),
    'registry=https://registry.npmjs.org/\nengine-strict=true\n',
  );

  writeJson(
    path.join(snapshot, 'package-lock.json'),
    pruneLock({ rootLock, newRoot, snapshot, workspaces, nameToDirectory }),
  );
  const restricted = Object.entries(
    readJson(path.join(snapshot, 'package-lock.json')).packages,
  ).filter(([, entry]) => !isPublic(entry));
  if (restricted.length > 0) {
    throw new Error(
      `The repository would install from a registry the public cannot read:\n  ${restricted
        .map(([key, entry]) => `${key} (${entry.resolved})`)
        .join('\n  ')}`,
    );
  }
  // eslint-disable-next-line no-console -- generator report
  console.log(
    `[standalone] ${workspaces.length} workspaces, ${
      Object.keys(dependencies).length
    } root dependencies`,
  );
};

/** Whether a lockfile entry installs without credentials. */
const isPublic = entry =>
  !entry.resolved ||
  !/^https?:\/\//.test(entry.resolved) ||
  entry.resolved.startsWith('https://registry.npmjs.org/');

const sortKeys = object =>
  Object.fromEntries(
    Object.entries(object).sort(([a], [b]) => a.localeCompare(b)),
  );

/** Bare package names imported by the workspaces' TypeScript and JavaScript. */
const importedPackages = (snapshot, workspaces) => {
  const names = new Set();
  for (const directory of workspaces) {
    const files = fs
      .readdirSync(path.join(snapshot, directory), { recursive: true })
      .filter(
        file =>
          /\.(?:[cm]?[jt]sx?)$/.test(file) &&
          !file.includes('node_modules') &&
          !file.startsWith('dist'),
      );
    for (const file of files) {
      const source = ts.preProcessFile(
        fs.readFileSync(path.join(snapshot, directory, file), 'utf8'),
        true,
        true,
      );
      for (const { fileName } of source.importedFiles) {
        if (fileName.startsWith('.') || fileName.startsWith('/')) continue;
        if (fileName.startsWith('node:')) continue;
        const parts = fileName.split('/');
        names.add(
          fileName.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0],
        );
      }
    }
  }
  return [...names].sort();
};

/**
 * The monorepo lockfile reduced to what the standalone root and its workspaces
 * install: every entry reachable from their declared dependencies, by Node's
 * lookup, with the ancestors of nested entries.
 */
const pruneLock = ({
  rootLock,
  newRoot,
  snapshot,
  workspaces,
  nameToDirectory,
}) => {
  const packages = rootLock.packages;
  const kept = new Set();
  const queue = [];
  const enqueue = key => {
    if (key && !kept.has(key)) {
      kept.add(key);
      queue.push(key);
    }
  };
  const requireFrom = (from, manifest, fields) => {
    for (const field of fields) {
      for (const name of Object.keys(manifest[field] ?? {})) {
        if (nameToDirectory[name]) continue;
        const key = resolveInLock(packages, from, name);
        if (key) enqueue(key);
        else if (
          field !== 'optionalDependencies' &&
          field !== 'peerDependencies'
        ) {
          throw new Error(
            `${
              from || '<root>'
            } needs ${name}, which the lockfile does not hold`,
          );
        }
      }
    }
  };

  requireFrom('', newRoot, DEPENDENCY_FIELDS);
  for (const directory of workspaces) {
    requireFrom(
      directory,
      readJson(path.join(snapshot, directory, 'package.json')),
      DEPENDENCY_FIELDS,
    );
  }
  while (queue.length > 0) {
    const key = queue.shift();
    requireFrom(key, packages[key], [
      'dependencies',
      'optionalDependencies',
      'peerDependencies',
    ]);
    // A nested entry lives inside its parent's directory. A workspace is never
    // queued this way: its requirements come from its rewritten manifest, not
    // from this repository's lockfile entry for it.
    const parent = key.lastIndexOf('/node_modules/');
    if (parent > 0 && key.startsWith('node_modules/')) {
      enqueue(key.slice(0, parent));
    }
  }

  const lockPackages = {
    '': {
      name: newRoot.name,
      license: newRoot.license,
      workspaces: newRoot.workspaces,
      dependencies: newRoot.dependencies,
      devDependencies: newRoot.devDependencies,
      engines: newRoot.engines,
    },
  };
  for (const directory of workspaces) {
    const manifest = readJson(path.join(snapshot, directory, 'package.json'));
    const entry = { ...packages[directory] };
    for (const field of DEPENDENCY_FIELDS) {
      if (manifest[field]) entry[field] = manifest[field];
      else delete entry[field];
    }
    entry.name = manifest.name;
    entry.version = manifest.version;
    lockPackages[directory] = entry;
    lockPackages[`node_modules/${manifest.name}`] = {
      resolved: directory,
      link: true,
    };
  }
  // Workspace links and nested installs belong only to workspaces present.
  const present = new Set(workspaces);
  const outsideWorkspaces = key =>
    (packages[key].link && !present.has(packages[key].resolved)) ||
    (/^(?:apps|packages)\//.test(key) &&
      ![...present].some(directory => key.startsWith(`${directory}/`)));
  for (const key of [...kept].sort()) {
    if (!lockPackages[key] && !outsideWorkspaces(key)) {
      lockPackages[key] = packages[key];
    }
  }
  return {
    name: newRoot.name,
    lockfileVersion: rootLock.lockfileVersion,
    requires: true,
    packages: lockPackages,
  };
};

const [command, target] = process.argv.slice(2);
if (command === 'allowlist' && target) writeAllowlist(path.resolve(target));
else if (command === 'transform' && target) transform(path.resolve(target));
else
  throw new Error(
    'Usage: standalone.mjs allowlist <file> | transform <snapshot-dir>',
  );
